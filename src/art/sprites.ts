const EMPTY = '.'.repeat(16);

/** Complète un dessin par le haut pour qu'il fasse 24 lignes, la base de la plante en ligne 22. */
function frame(rows: string[]): string[] {
  const out = [...rows];
  while (out.length < PLANT_H - 1) out.unshift(EMPTY);
  out.push(EMPTY);
  return out;
}

